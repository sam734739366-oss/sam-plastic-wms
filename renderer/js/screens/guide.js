const CONTACT = 'للاستفسار والمراجعة التواصل مع المبرمج / سام النبهاني 775158678';

function blockHtml(b) {
  if (b.kind === 'p') return `<p>${b.text}</p>`;
  if (b.kind === 'tip') return `<div class="guide-tip">${b.text}</div>`;
  if (b.kind === 'steps') {
    return `<h4>${b.title || ''}</h4><ol>${b.items.map((i) => `<li>${i}</li>`).join('')}</ol>`;
  }
  return '';
}

// نسخة الطباعة: كل الأقسام مفتوحة بالكامل مع وسوم خاصة بالطباعة
function buildPrintHtml() {
  let html = '';
  for (const s of SECTIONS) {
    if (!s.blocks || !s.blocks.length) continue;
    html += `<h2>${s.title}</h2>`;
    for (const b of s.blocks) {
      if (b.kind === 'p') html += `<p>${b.text}</p>`;
      else if (b.kind === 'tip') html += `<div class="g-tip">${b.text}</div>`;
      else if (b.kind === 'steps') {
        html += `<h3>${b.title || ''}</h3><ol>${b.items.map((i) => `<li>${i}</li>`).join('')}</ol>`;
      }
    }
  }
  html += `<div class="g-contact"><b>${CONTACT}</b></div>`;
  return html;
}

register('guide', {
  title: 'دليل المستخدم',
  async mount(el) {
    const sections = SECTIONS.filter((s) => s.blocks && s.blocks.length);
    const toc = sections.map((s, i) => `<a class="g-chip" href="#g-${s.id}">${i + 1}. ${s.title}</a>`).join('');
    const secs = sections.map((s, i) => `
      <details class="guide-sec" id="g-${s.id}" ${i === 0 ? 'open' : ''}>
        <summary><span class="g-num">${i + 1}</span><span class="g-title">${s.title}</span><span class="g-arrow">▾</span></summary>
        <div class="guide-body">${s.blocks.map(blockHtml).join('')}</div>
      </details>`).join('');
    el.innerHTML = `
      <div class="guide-hero">
        <h2>دليل المستخدم الكامل — الإصدار 2.0</h2>
        <p>كل شاشة وما فيها، وقواعد تسوية استلام الإنتاج (سليم / تالف قبل / تالف بعد وأين يستقر كل رقم)،
          وسلوك الحذف النهائي، والوحدات وفلاتر التقارير، والنسخ الاحتياطي والترقية والتحديث التلقائي والأدوار.</p>
        <div class="actions">
          <button id="btn-print-guide" class="btn light">طباعة الدليل كاملاً</button>
          <button id="btn-open-all" class="btn light">فتح كل الأقسام</button>
        </div>
      </div>
      <div class="guide-toc">${toc}</div>
      ${secs}
      <div class="guide-contact">
        <h3>التواصل والدعم الفني</h3>
        <p>${CONTACT}</p>
        <p class="tel" dir="ltr">775158678</p>
      </div>`;
    el.querySelector('#btn-print-guide').onclick = async (b) => {
      try {
        b.disabled = true;
        const settings = await api.invoke('settings:get');
        await api.invoke('print:open', { kind: 'guide', html: buildPrintHtml(), settings });
      } catch (e) { toast(String(e.message || e), 'err'); }
      b.disabled = false;
    };
    el.querySelector('#btn-open-all').onclick = () => {
      el.querySelectorAll('details.guide-sec').forEach((d) => { d.open = true; });
    };
  }
});
